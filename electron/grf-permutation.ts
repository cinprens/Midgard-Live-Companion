function permute(block: Uint8Array, table: number[]): void {
  const output = new Uint8Array(8);
  for (let bit = 0; bit < 64; bit++) {
    const source = table[bit]! - 1;
    if (block[source >> 3]! & (0x80 >> (source & 7))) output[bit >> 3] |= 0x80 >> (bit & 7);
  }
  block.set(output);
}
export function grfBlockTransform(block: Uint8Array): void {
  if (block.length !== 8) throw new Error('GRF blok uzunluğu geçersiz.');
  permute(block, IP);
  const indices = [((block[7]! << 5) | (block[4]! >> 3)) & 63, ((block[4]! << 1) | (block[5]! >> 7)) & 63,
    ((block[4]! << 5) | (block[5]! >> 3)) & 63, ((block[5]! << 1) | (block[6]! >> 7)) & 63,
    ((block[5]! << 5) | (block[6]! >> 3)) & 63, ((block[6]! << 1) | (block[7]! >> 7)) & 63,
    ((block[6]! << 5) | (block[7]! >> 3)) & 63, ((block[7]! << 1) | (block[4]! >> 7)) & 63];
  const combined = S.map((box, i) => (box[indices[i * 2]!]! & 0xf0) | (box[indices[i * 2 + 1]!]! & 15));
  for (let bit = 0; bit < 32; bit++) {
    const source = P[bit]! - 1;
    if (combined[source >> 3]! & (0x80 >> (source & 7))) block[bit >> 3] ^= 0x80 >> (bit & 7);
  }
  permute(block, FP);
}

/** Standard legacy GRF entry decoding only; no secret keys or protected GRFs. */
export function decodeGrfPermutation(data: Buffer, flags: number, compressedSize: number): void {
  if (flags === 1) return;
  if (flags !== 3 && flags !== 5) throw new Error('Bu GRF girdisinin koruma veya sıkıştırma türü desteklenmiyor.');
  const digits = String(compressedSize).length;
  const cycle = digits < 3 ? 3 : digits < 5 ? digits + 1 : digits < 7 ? digits + 9 : digits + 15;
  let skipped = 0;
  for (let at = 0, block = 0; at + 8 <= data.length; at += 8, block++) {
    const chunk = data.subarray(at, at + 8);
    if (block < 20 || (flags === 3 && block % cycle === 0)) grfBlockTransform(chunk);
    else {
      if (flags === 3 && skipped === 7) {
        const before = Buffer.from(chunk);
        chunk.set([before[3]!,before[4]!,before[6]!,before[0]!,before[1]!,before[2]!,before[5]!,substitutions.get(before[7]!) ?? before[7]!]);
        skipped = 0;
      }
      skipped++;
    }
  }
}
